using System.Text;

namespace NodeRunner.Editor;

// A FiveM resource made of map files: a folder named after the resource, with an fxmanifest.lua and a "stream" folder
// holding the .ymap files (streamed files with a game name replace the game's file of that name).
public static class FiveMResource
{
    public const string ManifestFileName = "fxmanifest.lua";
    public const string StreamFolderName = "stream";

    public const string GeneratedMarker = "-- Generated by NodeRunner";

    public const string DefaultName = "noderunner_map";

    // Resource names usable everywhere (server.cfg "ensure", folder name, every file system): lower-case letters,
    // digits, '_' and '-', starting with a letter or a digit, at most 64 characters.
    public static bool IsValidName(string name) =>
        name.Length is > 0 and <= 64
        && (char.IsAsciiLetterLower(name[0]) || char.IsAsciiDigit(name[0]))
        && name.All(c => char.IsAsciiLetterLower(c) || char.IsAsciiDigit(c) || c is '_' or '-');

    public static string ToValidName(string text)
    {
        var sb = new StringBuilder();
        foreach (char c in text.Trim().ToLowerInvariant().Normalize(NormalizationForm.FormD))
        {
            if (char.IsAsciiLetterLower(c) || char.IsAsciiDigit(c) || c is '_' or '-')
                sb.Append(c);
            else if (char.GetUnicodeCategory(c) != System.Globalization.UnicodeCategory.NonSpacingMark && sb.Length > 0 && sb[^1] != '_')
                sb.Append('_'); // Accents are dropped (é -> e), everything else becomes a separator.
        }
        string name = sb.ToString().Trim('_', '-');
        if (name.Length > 64)
            name = name[..64].TrimEnd('_', '-');
        return name.Length > 0 ? name : DefaultName;
    }

    public static bool IsGeneratedManifest(string text) =>
        text.TrimStart('﻿').StartsWith(GeneratedMarker, StringComparison.Ordinal);

    public static string BuildManifest(string author, string version, IEnumerable<string> mapFiles)
    {
        var sb = new StringBuilder();
        sb.Append(GeneratedMarker).Append(' ').Append(version).Append(" (").Append(author).Append(")\n");
        sb.Append("-- Modified map files (stream folder):\n");
        foreach (var file in mapFiles.Order(StringComparer.OrdinalIgnoreCase))
            sb.Append("--   ").Append(file).Append('\n');
        sb.Append('\n');
        sb.Append("fx_version 'cerulean'\n");
        sb.Append("game 'gta5'\n");
        sb.Append('\n');
        sb.Append("author '").Append(author.Replace("'", "")).Append("'\n");
        sb.Append("description 'Map edited with NodeRunner'\n");
        sb.Append("version '1.0.0'\n");
        sb.Append('\n');
        sb.Append("this_is_a_map 'yes'\n");
        return sb.ToString();
    }
}
